_ALL_SENTIMENT: dict[str, float] = {**POSITIVE_WORDS, **NEGATIVE_WORDS}

#: 按词长降序，保证「喜欢」不会先把「不喜欢」吃掉
SENTIMENT_KEYS_BY_LENGTH: tuple[str, ...] = tuple(
    sorted(_ALL_SENTIMENT, key=len, reverse=True)
)

MAX_POSITIVE_KEY_LEN = max((len(k) for k in POSITIVE_WORDS), default=1)
MAX_NEGATIVE_KEY_LEN = max((len(k) for k in NEGATIVE_WORDS), default=1)


def sentiment_weight(word: str) -> float:
    return _ALL_SENTIMENT.get(word, 0.0)


def is_positive(word: str) -> bool:
    return word in POSITIVE_WORDS


def is_negative(word: str) -> bool:
    return word in NEGATIVE_WORDS


def all_intimate_terms() -> list[tuple[str, str]]:
    """返回 ``[(词, 亲密档位), ...]``，按档位强度降序。"""
    out: list[tuple[str, str]] = []
    for tier, words in INTIMATE_TERMS.items():
        for w in words:
            out.append((w, tier))
    return out